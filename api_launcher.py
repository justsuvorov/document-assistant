#!/usr/bin/env python
"""
Launcher для API сервиса.
Проверяет наличие .env файла и создаёт его если нужно.
"""
import os
import sys
from pathlib import Path

# Дефолтные значения для .env
DEFAULT_ENV = """# ── PATHS ────────────────────────────────────────────────────────────────────
NORMATIVE_BASE=./normative_base
EXAMPLES_PATH=./examples

# ── AI PROVIDER ───────────────────────────────────────────────────────────────
AI_TEMPERATURE=0.2

# ── Qwen Model (OpenAI-compatible API) ─────────────────────────────────────────
QWEN_API_URL=https://model-1.ai-api.vsk.ru/v1/completions
QWEN_MODEL_NAME=Qwen3.6-35B-A3B-NVFP4
QWEN_MAX_TOKENS=100000
QWEN_NUM_CTX=400000

# ── Обработка документов ───────────────────────────────────────────────────────
LLM_MAX_CHARS=2200000
LLM_MAX_SECTIONS=300
LLM_MAX_CHUNKS=0
LLM_BATCH_SIZE=25

# ── PROMPT ─────────────────────────────────────────────────────────────────────
AI_ROLE=Ты — опытный специалист по страхованию. Твоя задача — точно сопоставить требования клиента с нормативными программами страхования и подготовить структурированный ответ.

AI_PROMPT_TEMPLATE={role}\\n\\n## НОРМАТИВНАЯ БАЗА (ПРОГРАММЫ СТРАХОВАНИЯ):\\n{normative_base}\\n\\n## ПРИМЕРЫ ЭТАЛОННЫХ ОТВЕТОВ:\\n{examples}\\n\\n## ЗАПРОС КЛИЕНТА:\\n{source_text}\\n\\n## ЗАДАЧА:\\n1. Из нормативной базы выбери программу страхования, наиболее соответствующую требованиям клиента.\\n2. Для КАЖДОЙ строки из таблицы запроса клиента создай ровно одну строку в таблице ответа.\\n   ВАЖНО: не объединяй строки, не пропускай строки, не добавляй лишние строки.\\n   Количество строк в ответе должно строго совпадать с количеством строк в запросе.\\n3. Для каждой строки укажи статус покрытия в выбранной программе:\\n   - Есть — требование полностью покрывается программой\\n   - Нет — требование отсутствует в программе\\n   - Частично — требование покрывается частично (поясни в комментарии)\\n4. Оформи ответ СРАЗУ в виде таблицы (без вводного текста и преамбулы) со столбцами:\\n   | Требование клиента | Покрытие по программе | Статус | Комментарий |\\n5. После таблицы добавь краткое резюме: выбранная программа, ключевые расхождения и рекомендации.\\n\\n## ОТВЕТ:
"""

def ensure_env():
    """Проверить/создать .env файл если его нет."""
    env_path = Path(".env")

    if not env_path.exists():
        print("[INFO] Файл .env не найден, создаю с дефолтными значениями...")
        env_path.write_text(DEFAULT_ENV, encoding="utf-8")
        print(f"[INFO] Создан .env в {env_path.absolute()}")
        print("[WARNING] ⚠️  Пожалуйста, отредактируй .env если нужны другие параметры!")
        print()

if __name__ == "__main__":
    try:
        # Проверяем/создаём .env
        ensure_env()

        # Импортируем и запускаем приложение
        import uvicorn

        print("[INFO] Запуск API сервиса на http://0.0.0.0:8001...")
        print()

        uvicorn.run(
            "main:app",
            host="0.0.0.0",
            port=8001,
            workers=2,
            log_level="info",
        )
    except Exception as e:
        print(f"[ERROR] {e}", file=sys.stderr)
        print()
        print("Нажми Enter для выхода...", file=sys.stderr)
        input()
        sys.exit(1)
