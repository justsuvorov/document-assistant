"""Промпт для заполнения по ID.

Шаблон состоит из двух частей:
  - смысловая (роль, нормативка, что считать «Есть/Нет/Частично») —
    ``AI_FILL_PROMPT_TEMPLATE`` или ``DEFAULT_FILL_TEMPLATE``;
  - формат ответа — ``RESPONSE_CONTRACT``, всегда добавляется кодом в конец.
    От него зависит разбор ответа, поэтому через настройку он не меняется.

Нормативная база стоит в начале, запрос клиента — в конце: при нескольких
частях начало промпта одинаковое, и сервер модели с кэшем префикса не
пересчитывает его заново.
"""

from __future__ import annotations

from document_assistant.ai.promt_builders import PromptEngine

DEFAULT_FILL_TEMPLATE = """{role}

## НОРМАТИВНАЯ БАЗА (ПРОГРАММЫ СТРАХОВАНИЯ):
{normative_base}

## ПРИМЕРЫ ЭТАЛОННЫХ ОТВЕТОВ:
{examples}

## ЗАДАЧА:
1. Из нормативной базы выбери программу страхования, наиболее соответствующую требованиям клиента.
2. Для каждой строки запроса, у которой есть ID, укажи покрытие в выбранной программе и статус:
   - Есть — требование полностью покрывается программой
   - Нет — требование отсутствует в программе
   - Частично — требование покрывается частично (поясни в комментарии)
   Строке-заголовку раздела без самостоятельного требования поставь статус «—».

## ПРАВИЛА ОЦЕНКИ:
1. Опирайся только на текст выбранной программы. Ограничение или условие (лимит, «по согласованию», «по медицинским показаниям», место оказания) указывай, только если оно прямо есть в программе, и приводи цитату. Не добавляй условий, которых в программе нет: «плановость», «жизненные показания», «обычно», «как правило».
2. Общее и частное:
   - если программа покрывает общую категорию (например, «физиотерапия», «консультации врачей других специальностей в соответствии с лицензией медицинской организации») и не исключает конкретный вид, частный вид внутри этой категории покрыт — статус Есть, даже если он не назван дословно;
   - если программа даёт закрытый перечень (например, что именно выполняется на дому), а требование шире — статус Частично, в комментарии «в объёме: …» с перечнем из программы;
   - не считай требование покрытым только потому, что покрыто похожее по названию или родственное (иммунограмма ≠ иммунологический статус, седация ≠ анестезия, если программа их различает).
3. Исключения применяй дословно: исключено только то, что прямо названо (заболевание, стадия, форма, метод). Исключение отдельных заболеваний не исключает всю группу: исключение глубоких микозов не исключает лечение микозов, исключение ряда кожных заболеваний не исключает все заболевания кожи.
4. Диагностику и лечение оценивай раздельно: если лечение исключено, а диагностика нет — статус Частично, «покрывается только диагностика».
5. Если программа ограничивает условия оказания (амбулаторно, стационар, дневной стационар, на дому, санаторно-курортное лечение), обязательно укажи это в комментарии.
6. Если требование состоит из нескольких частей (через «/», запятую или «и»), оцени каждую часть и укажи, какие покрыты.
7. «Покрытие по программе» — раздел или пункт программы и короткая дословная цитата, на которой основан ответ. Не пиши туда только название программы.
8. Учитывай инструкции клиента в строках без ID (например, когда отвечать «да», а когда «с ограничениями») и смысл соседних строк и заголовков разделов.

## ЗАПРОС КЛИЕНТА (таблица: ID строки, текст требования, затем столбцы-контекст):
{source_text}"""

# Без фигурных скобок: шаблон проходит через str.format.
RESPONSE_CONTRACT = """

## ФОРМАТ ОТВЕТА (обязателен):
Ответь ОДНОЙ markdown-таблицей, без вводного текста, со столбцами:
| ID | Требование (начало) | Покрытие по программе | Статус | Комментарий |
Правила:
- ровно одна строка ответа на каждый ID из запроса, в том же порядке;
- ID копируй точно как в запросе (например, R0007); не пропускай, не повторяй и не придумывай ID;
- оценивай текст из столбца «Требование»; столбцы «Контекст» — раздел, номер, условия клиента: учитывай их смысл, но не путай с требованием;
- строки запроса без ID — инструкции клиента, заголовки разделов и детализация к соседним строкам; отдельно на них не отвечай, но учитывай их смысл;
- «Требование (начало)» — первые 8–12 слов из столбца «Требование» этой строки, дословно, без изменений (короткий текст — целиком); не бери текст из столбцов «Контекст»;
- «Статус» — одно из: Есть, Нет, Частично, —;
- внутри ячеек не используй символ «|» и переносы строк.
После таблицы добавь раздел с заголовком «## Резюме»: выбранная программа, ключевые расхождения, рекомендации.

## ОТВЕТ:
"""


class FillPromptBuilder:
    def __init__(self, role: str, template: str, normative_base: str, num_ctx: int,
                 output_tokens: int | None = None):
        self._engine = PromptEngine(
            role=role,
            template=(template or DEFAULT_FILL_TEMPLATE) + RESPONSE_CONTRACT,
            normative_base=normative_base,
            num_ctx=num_ctx,
            output_tokens=output_tokens,
        )

    def build(self, table_markdown: str) -> str:
        return self._engine.build(source_text=table_markdown, examples=[])
